        function openModal() {
            document.getElementById('contactModal').classList.add('active');
            document.body.style.overflow = 'hidden';
        }

        function closeModal() {
            document.getElementById('contactModal').classList.remove('active');
            document.body.style.overflow = 'auto';
            
            // Reset form and messages after closing
            setTimeout(() => {
                document.getElementById('contactForm').style.display = 'block';
                document.getElementById('successMessage').classList.remove('active');
                document.querySelector('form').reset();
            }, 300);
        }

        function handleSubmit(event) {
            event.preventDefault();
            
            // Get form data
            const formData = {
                firstName: document.getElementById('firstName').value,
                lastName: document.getElementById('lastName').value,
                email: document.getElementById('email').value,
                phone: document.getElementById('phone').value,
                company: document.getElementById('company').value,
                message: document.getElementById('message').value
            };
            
            // Disable submit button to prevent double submission
            const submitBtn = event.target.querySelector('.submit-btn');
            submitBtn.disabled = true;
            submitBtn.textContent = 'Sending...';
            
            // Send email using Formspree
            fetch('https://formspree.io/f/xjkvekge', {
                method: 'POST',
                headers: {
                    'Content-Type': 'application/json'
                },
                body: JSON.stringify(formData)
            })
            .then(response => {
                if (response.ok) {
                    // Show success message
                    document.getElementById('contactForm').style.display = 'none';
                    document.getElementById('successMessage').classList.add('active');
                } else {
                    throw new Error('Form submission failed');
                }
            })
            .catch(error => {
                console.error('Error:', error);
                alert('There was an error sending your message. Please try again or contact us directly at julia.cointa@gmail.com');
                submitBtn.disabled = false;
                submitBtn.textContent = 'Submit';
            });
        }

        // Close modal when clicking outside
        document.getElementById('contactModal').addEventListener('click', function(e) {
            if (e.target === this) {
                closeModal();
            }
        });

        // Close modal on Escape key
        document.addEventListener('keydown', function(e) {
            if (e.key === 'Escape') {
                closeModal();
            }
        });

        // Animated counter for results
        function animateCounter(element, target, duration = 2000) {
            const start = 0;
            const increment = target / (duration / 16); // 60 FPS
            let current = start;
            
            const card = element.closest('.result-card');
            card.classList.add('animating');
            
            const timer = setInterval(() => {
                current += increment;
                if (current >= target) {
                    current = target;
                    clearInterval(timer);
                    card.classList.remove('animating');
                }
                element.textContent = Math.floor(current) + '%';
            }, 16);
        }

        // Intersection Observer to trigger animation when scrolled into view
        const observerOptions = {
            threshold: 0.5,
            rootMargin: '0px'
        };

        const observer = new IntersectionObserver((entries) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    const metricElement = entry.target.querySelector('.metric');
                    if (metricElement && !metricElement.classList.contains('animated')) {
                        const target = parseInt(metricElement.getAttribute('data-target'));
                        animateCounter(metricElement, target);
                        metricElement.classList.add('animated');
                    }
                }
            });
        }, observerOptions);

        // Observe all result cards
        document.addEventListener('DOMContentLoaded', () => {
            const resultCards = document.querySelectorAll('.result-card');
            resultCards.forEach(card => observer.observe(card));
        });
